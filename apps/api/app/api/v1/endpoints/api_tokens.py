from app.api.deps import get_current_user
from app.core.security import decrypt_secret, encrypt_secret
from app.db.session import get_db
from app.models.user import UserModel
from app.schemas.api_token import (
    ApiTokenCreatedResponse,
    ApiTokenCreateRequest,
    ApiTokenListResponse,
    ApiTokenResponse,
)
from app.services.api_token import ApiTokenService
from fastapi import APIRouter, Depends, status
from novelova_core.models import ApiResponse
from pydantic import BaseModel
from sqlalchemy.ext.asyncio import AsyncSession

router = APIRouter()


class HfTokenStatusResponse(BaseModel):
    has_token: bool
    token_masked: str | None = None


class HfTokenUpdateRequest(BaseModel):
    hf_token: str | None = None


def _mask_hf_token(encrypted_val: str | None) -> str | None:
    if not encrypted_val:
        return None
    try:
        raw = decrypt_secret(encrypted_val)
    except Exception:
        return "hf_••••••••"
    if not raw:
        return None
    if len(raw) <= 8:
        return "••••••••"
    return f"{raw[:4]}••••••••{raw[-4:]}"


@router.get("/hf-token", response_model=ApiResponse[HfTokenStatusResponse])
async def get_hf_token_status(
    current_user: UserModel = Depends(get_current_user),
):
    """Retrieve whether the current user has a personal Hugging Face token configured (masked)."""
    return ApiResponse(
        success=True,
        data=HfTokenStatusResponse(
            has_token=bool(current_user.hf_token_encrypted),
            token_masked=_mask_hf_token(current_user.hf_token_encrypted),
        ),
        message="Hugging Face token status retrieved",
    )


@router.put("/hf-token", response_model=ApiResponse[HfTokenStatusResponse])
async def update_hf_token(
    payload: HfTokenUpdateRequest,
    current_user: UserModel = Depends(get_current_user),
    db: AsyncSession = Depends(get_db),
):
    """Save or clear the current user's personal Hugging Face token (encrypted at rest)."""
    raw = (payload.hf_token or "").strip()
    if not raw:
        current_user.hf_token_encrypted = None
    elif "•" not in raw:
        current_user.hf_token_encrypted = encrypt_secret(raw)

    await db.commit()
    await db.refresh(current_user)
    return ApiResponse(
        success=True,
        data=HfTokenStatusResponse(
            has_token=bool(current_user.hf_token_encrypted),
            token_masked=_mask_hf_token(current_user.hf_token_encrypted),
        ),
        message="Hugging Face token saved successfully" if current_user.hf_token_encrypted else "Hugging Face token cleared",
    )


@router.delete("/hf-token", response_model=ApiResponse[HfTokenStatusResponse])
async def delete_hf_token(
    current_user: UserModel = Depends(get_current_user),
    db: AsyncSession = Depends(get_db),
):
    """Remove the current user's stored Hugging Face token."""
    current_user.hf_token_encrypted = None
    await db.commit()
    await db.refresh(current_user)
    return ApiResponse(
        success=True,
        data=HfTokenStatusResponse(has_token=False, token_masked=None),
        message="Hugging Face token removed",
    )


@router.get("", response_model=ApiResponse[ApiTokenListResponse])
async def list_api_tokens(
    current_user: UserModel = Depends(get_current_user),
    db: AsyncSession = Depends(get_db),
):
    """List all API tokens generated by the current user."""
    tokens = await ApiTokenService.list_tokens(user_id=current_user.id, db=db)
    data = ApiTokenListResponse(
        tokens=[ApiTokenResponse.model_validate(t) for t in tokens],
        total=len(tokens),
    )
    return ApiResponse(
        success=True,
        data=data,
        message="API tokens retrieved successfully",
    )


@router.post("", response_model=ApiResponse[ApiTokenCreatedResponse], status_code=status.HTTP_201_CREATED)
async def create_api_token(
    payload: ApiTokenCreateRequest,
    current_user: UserModel = Depends(get_current_user),
    db: AsyncSession = Depends(get_db),
):
    """
    Generate a new long-lived API token for CLI or AI agent operation.
    The raw token string is returned ONLY ONCE in this response.
    """
    token_obj, raw_token = await ApiTokenService.create_token(
        user_id=current_user.id,
        dto=payload,
        db=db,
    )
    res_data = ApiTokenCreatedResponse(
        id=token_obj.id,
        name=token_obj.name,
        token_prefix=token_obj.token_prefix,
        expires_at=token_obj.expires_at,
        rate_limit_rpm=token_obj.rate_limit_rpm,
        is_active=token_obj.is_active,
        last_used_at=token_obj.last_used_at,
        created_at=token_obj.created_at,
        token=raw_token,
    )
    return ApiResponse(
        success=True,
        data=res_data,
        message="API token created successfully. Store the secret token securely; it cannot be shown again.",
    )


@router.delete("/{token_id}", response_model=ApiResponse[dict])
async def revoke_api_token(
    token_id: str,
    current_user: UserModel = Depends(get_current_user),
    db: AsyncSession = Depends(get_db),
):
    """Revoke and delete an API token."""
    await ApiTokenService.revoke_token(user_id=current_user.id, token_id=token_id, db=db)
    return ApiResponse(
        success=True,
        data={"revoked_token_id": token_id},
        message="API token revoked successfully",
    )
