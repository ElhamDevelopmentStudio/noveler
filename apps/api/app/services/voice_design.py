def normalize_audio(wav: np.ndarray, target_peak: float = 0.89) -> np.ndarray:
    wav = np.asarray(wav, dtype=np.float32).squeeze()
    peak = float(np.max(np.abs(wav))) if wav.size > 0 else 0.0
    if peak > 1e-6:
        wav = wav * (target_peak / peak)
    return wav

