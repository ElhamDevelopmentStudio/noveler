class VoiceDesignService:
    @classmethod
    def _build_default_prompt_and_lines(cls, char: CharacterModel) -> tuple[str, list[str]]:
        """Fallback prompt & calibration lines when a character has no dossier yet."""
        dossier = char.dossier or {}
        prompt = dossier.get("voice_design_prompt")
        if not prompt:
            gender_word = "woman" if (char.gender or "").lower() == "female" else "man"
            role_hint = f", {char.role_description}" if char.role_description else ""
            prompt = (
                f"A clear, expressive adult {gender_word} with a natural, well-articulated audiobook voice"
                f"{role_hint}. Measured pacing and steady vocal timbre."
            )
        sample_lines = dossier.get("sample_lines")
        if not sample_lines or not isinstance(sample_lines, list):
            sample_lines = [
                f"We have waited long enough to settle this matter properly.",
                f"Listen closely, because I will only explain this once.",
            ]
        return prompt, [str(line).strip() for line in sample_lines if str(line).strip()]

    @classmethod
    async def _select_kaggle_account(
        cls,
        user_id: str,
        db: AsyncSession,
        kaggle_account_id: str | None = None,
    ) -> KaggleAccountModel:
        if kaggle_account_id:
            acc = await db.get(KaggleAccountModel, kaggle_account_id)
            if not acc or acc.user_id != user_id:
                raise NotFoundError(f"Kaggle account '{kaggle_account_id}' not found")
            return acc

        stmt = (
            select(KaggleAccountModel)
            .where(
                KaggleAccountModel.user_id == user_id,
                KaggleAccountModel.is_active.is_(True),
            )
            .order_by(KaggleAccountModel.created_at.asc())
        )
        accounts = list((await db.execute(stmt)).scalars().all())
        if not accounts:
            raise ValidationError(
                "No active Kaggle GPU account configured. Please add a Kaggle account in Profile settings."
            )
        available = [a for a in accounts if a.status == "available"]
        return available[0] if available else accounts[0]

    @classmethod
    async def start_voice_design_job(
        cls,
        payload: VoiceDesignRequestSchema,
        user_id: str,
        db: AsyncSession,
    ) -> VoiceDesignJobModel:
        """
        Launch a batched Kaggle Qwen3-TTS-12Hz-1.7B-VoiceDesign job for manually selected characters.
        Auto-builds missing character dossiers if enabled, uploads manifest to R2, dispatches Kaggle notebook,
        and spawns a background monitor that registers completed clips into VoiceModel.
        """
        project = await db.get(ProjectModel, payload.project_id)
        if not project:
            raise NotFoundError(f"Project '{payload.project_id}' not found")

        # Normalize requested items from either `items` or `character_ids`
        requested_items: list[VoiceDesignCharacterInput] = []
        if payload.items:
            requested_items = list(payload.items)
        elif payload.character_ids:
            requested_items = [VoiceDesignCharacterInput(character_id=cid) for cid in payload.character_ids]

        if not requested_items:
            raise ValidationError("At least one character must be selected for VoiceDesign.")

        char_ids = [item.character_id for item in requested_items]
        stmt = select(CharacterModel).where(
            CharacterModel.project_id == payload.project_id,
            CharacterModel.id.in_(char_ids),
        )
        chars_by_id = {c.id: c for c in (await db.execute(stmt)).scalars().all()}
        missing = [cid for cid in char_ids if cid not in chars_by_id]
        if missing:
            raise NotFoundError(f"Character(s) not found in project: {', '.join(missing)}")

        # Optionally build missing dossiers when no custom prompt override was supplied
        if payload.auto_build_missing_dossiers and settings.DEEPSEEK_API_KEY:
            for item in requested_items:
                char = chars_by_id[item.character_id]
                if not item.voice_design_prompt and not (char.dossier or {}).get("voice_design_prompt"):
                    try:
                        await CharacterDossierService.build_character_dossier(
                            project_id=payload.project_id,
                            character=char,
                            db=db,
                        )
                    except Exception as exc:
                        logger.warning("Auto-dossier fallback for '%s': %s", char.name, exc)

        account = await cls._select_kaggle_account(
            user_id=user_id,
            db=db,
            kaggle_account_id=payload.kaggle_account_id,
        )

        character_configs: list[dict[str, Any]] = []
        initial_results: list[dict[str, Any]] = []
        for item in requested_items:
            char = chars_by_id[item.character_id]
            default_prompt, default_lines = cls._build_default_prompt_and_lines(char)
            final_prompt = (item.voice_design_prompt or "").strip() or default_prompt
            final_lines = (
                [l.strip() for l in item.sample_lines if l.strip()]
                if item.sample_lines
                else default_lines
            )
            voice_name = (item.voice_name or "").strip() or char.name

            character_configs.append(
                {
                    "character_id": char.id,
                    "character_name": char.name,
                    "voice_name": voice_name,
                    "gender": char.gender or "neutral",
                    "voice_design_prompt": final_prompt,
                    "sample_lines": final_lines,
                }
            )
            initial_results.append(
                {
                    "character_id": char.id,
                    "character_name": char.name,
                    "voice_name": voice_name,
                    "status": "pending",
                    "voice_design_prompt": final_prompt,
                    "auto_assigned": False,
                }
            )

        job_id = str(uuid.uuid4())
        job = VoiceDesignJobModel(
            id=job_id,
            project_id=payload.project_id,
            user_id=user_id,
            kaggle_account_id=account.id,
            status="pending",
            auto_assign=payload.auto_assign,
            is_global=payload.is_global,
            cache_to_dataset=payload.cache_to_dataset,
            total_characters=len(character_configs),
            completed_characters=0,
            progress_percentage=0,
            current_step=f"Dispatching Qwen3-TTS-12Hz-1.7B-VoiceDesign on @{account.username}...",
            target_character_ids=char_ids,
            character_configs=character_configs,
            results=initial_results,
        )
        db.add(job)
        await db.commit()
        await db.refresh(job)

        # Upload manifest to R2 and push Kaggle kernel
        await cls._dispatch_kaggle_notebook(job=job, account=account, db=db)

        # Spawn background monitor task
        task = asyncio.create_task(cls._monitor_voice_design_job(job.id, account.id))
        ACTIVE_VOICE_DESIGN_TASKS[job.id] = task
        task.add_done_callback(lambda _: ACTIVE_VOICE_DESIGN_TASKS.pop(job.id, None))
        return job

    @classmethod
    async def _dispatch_kaggle_notebook(
        cls,
        job: VoiceDesignJobModel,
        account: KaggleAccountModel,
        db: AsyncSession,
    ) -> None:
        """Upload VoiceDesign manifest to R2 and push the batched Kaggle GPU kernel."""
        manifest = {
            "job_id": job.id,
            "project_id": job.project_id,
            "model_id": QWEN_VOICE_DESIGN_MODEL_ID,
            "characters": job.character_configs,
            "created_at": datetime.now(UTC).isoformat(),
        }

        s3 = get_s3_client()
        if s3 and settings.is_r2_configured:
            s3.put_object(
                Bucket=settings.R2_BUCKET,
                Key=f"jobs/voice-design/{job.id}/manifest.json",
                Body=json.dumps(manifest).encode("utf-8"),
                ContentType="application/json",
            )

        raw_key = decrypt_secret(account.encrypted_key)
        is_dummy = raw_key.startswith("KGAT_testdummy") or "dummy" in raw_key.lower()

        dataset_sources: list[str] = []
        if job.cache_to_dataset:
            dataset_sources.append(f"{account.username}/{VOICE_DESIGN_DATASET_SLUG}")
            if getattr(account, "dataset_ref", None):
                dataset_sources.append(account.dataset_ref)

        script_code = build_voice_design_kaggle_script(
            job_id=job.id,
            project_id=job.project_id,
            r2_endpoint=settings.r2_effective_endpoint,
            r2_bucket=settings.R2_BUCKET,
            r2_access_key=settings.R2_ACCESS_KEY_ID,
            r2_secret_key=settings.R2_SECRET_ACCESS_KEY,
            cache_to_dataset=job.cache_to_dataset,
            kaggle_dataset_ref=dataset_sources[0] if dataset_sources else None,
        )

        if not is_dummy:
            def _sync_push():
                from kaggle.api.kaggle_api_extended import KaggleApi

                api = KaggleApi()
                os.environ["KAGGLE_USERNAME"] = account.username
                if raw_key.startswith("KGAT_"):
                    os.environ["KAGGLE_API_TOKEN"] = raw_key
                    os.environ.pop("KAGGLE_KEY", None)
                else:
                    os.environ["KAGGLE_KEY"] = raw_key
                    os.environ.pop("KAGGLE_API_TOKEN", None)
                api.authenticate()

                # Keep only dataset sources that actually exist on Kaggle so push never 404s
                valid_datasets: list[str] = []
                for ds_ref in dataset_sources:
                    try:
                        owner, slug = ds_ref.split("/", 1)
                        found = api.dataset_list(user=owner, search=slug)
                        if any(getattr(d, "ref", "").endswith(slug) for d in found):
                            valid_datasets.append(ds_ref)
                    except Exception:
                        continue

                with tempfile.TemporaryDirectory() as tmp_dir:
                    script_path = os.path.join(tmp_dir, "voice_design_worker.py")
                    with open(script_path, "w", encoding="utf-8") as f:
                        f.write(script_code)
                    meta = {
                        "id": f"{account.username}/novelova-voice-design-{job.id[:8]}",
                        "title": f"Novelova VoiceDesign {job.id[:8]}",
                        "code_file": "voice_design_worker.py",
                        "language": "python",
                        "kernel_type": "script",
                        "is_private": True,
                        "enable_gpu": True,
                        "enable_internet": True,
                        "dataset_sources": valid_datasets,
                        "competition_sources": [],
                        "kernel_sources": [],
                    }
                    with open(os.path.join(tmp_dir, "kernel-metadata.json"), "w", encoding="utf-8") as f:
                        json.dump(meta, f)
                    api.kernels_push(tmp_dir)

            await asyncio.to_thread(_sync_push)

        account.status = "in_use"
        job.status = "running"
        job.current_step = f"Kaggle GPU notebook running for {job.total_characters} character(s)..."
        await db.commit()
        await db.refresh(job)

    @classmethod
    async def ingest_receipt_into_voices(
        cls,
        job_id: str,
        receipt: dict[str, Any],
        db: AsyncSession,
    ) -> VoiceDesignJobModel:
        """
        Idempotently register completed Kaggle VoiceDesign clips into VoiceModel
        (with character name + VoiceDesign prompt as description) and auto-assign if enabled.
        """
        job = await db.get(VoiceDesignJobModel, job_id)
        if not job:
            raise NotFoundError(f"VoiceDesign job '{job_id}' not found")

        existing_by_char = {r["character_id"]: dict(r) for r in (job.results or []) if "character_id" in r}
        updated_results: list[dict[str, Any]] = []
        completed_count = 0

        for item in receipt.get("results", []):
            char_id = item["character_id"]
            prev = existing_by_char.get(char_id, {})
            status = item.get("status", "pending")

            if status == "completed":
                completed_count += 1
                voice_id = prev.get("voice_id")
                audio_url = prev.get("audio_url")
                auto_assigned = bool(prev.get("auto_assigned", False))

                # Register VoiceModel once per character
                if not voice_id and item.get("audio_storage_key"):
                    voice = VoiceModel(
                        id=str(uuid.uuid4()),
                        user_id=job.user_id,
                        project_id=None if job.is_global else job.project_id,
                        name=item.get("voice_name") or item.get("character_name") or "Designed Voice",
                        gender=(item.get("gender") or "neutral").lower(),
                        is_global=job.is_global,
                        audio_storage_key=item["audio_storage_key"],
                        reference_text=item.get("reference_text"),
                        description=item.get("voice_design_prompt"),
                        duration_seconds=item.get("duration_seconds"),
                    )
                    db.add(voice)
                    await db.flush()
                    voice_id = voice.id
                    audio_url = VoiceService.get_presigned_url(voice.audio_storage_key)

                    if job.auto_assign:
                        char = await db.get(CharacterModel, char_id)
                        if char:
                            char.assigned_voice_id = voice.id
                            char.assigned_voice_name = voice.name
                            char.updated_at = datetime.now(UTC)
                            auto_assigned = True

                updated_results.append(
                    {
                        "character_id": char_id,
                        "character_name": item.get("character_name") or prev.get("character_name", ""),
                        "status": "completed",
                        "voice_id": voice_id,
                        "voice_name": item.get("voice_name") or item.get("character_name"),
                        "audio_url": audio_url,
                        "voice_design_prompt": item.get("voice_design_prompt"),
                        "auto_assigned": auto_assigned,
                    }
                )
            elif status == "failed":
                completed_count += 1
                updated_results.append(
                    {
                        "character_id": char_id,
                        "character_name": item.get("character_name") or prev.get("character_name", ""),
                        "status": "failed",
                        "voice_design_prompt": item.get("voice_design_prompt"),
                        "auto_assigned": False,
                        "error": item.get("error") or "Voice generation failed",
                    }
                )
            else:
                updated_results.append(prev or item)

        job.results = updated_results
        job.completed_characters = completed_count
        job.progress_percentage = (
            int(round((completed_count / max(1, job.total_characters)) * 100))
            if job.total_characters > 0
            else 100
        )
        if receipt.get("current_step"):
            job.current_step = receipt["current_step"]
        if receipt.get("status") in ("completed", "failed"):
            job.status = receipt["status"]
            if receipt.get("error_message"):
                job.error_message = receipt["error_message"]
        job.updated_at = datetime.now(UTC)
        await db.commit()
        await db.refresh(job)
        return job

    @classmethod
    async def _monitor_voice_design_job(cls, job_id: str, account_id: str) -> None:
        """Poll R2 for Kaggle VoiceDesign receipts until completed/failed or timeout."""
        factory = get_session_factory()
        receipt_key = f"jobs/voice-design/{job_id}/receipt.json"
        max_polls = 360  # up to 30 minutes at 5s interval

        try:
            for _ in range(max_polls):
                await asyncio.sleep(5.0)
                s3 = get_s3_client()
                if not s3 or not settings.is_r2_configured:
                    break

                def _fetch_receipt():
                    try:
                        obj = s3.get_object(Bucket=settings.R2_BUCKET, Key=receipt_key)
                        return json.loads(obj["Body"].read().decode("utf-8"))
                    except Exception:
                        return None

                receipt = await asyncio.to_thread(_fetch_receipt)
                if not receipt:
                    continue

                async with factory() as db:
                    job = await cls.ingest_receipt_into_voices(job_id, receipt, db)
                    if job.status in ("completed", "failed", "cancelled"):
                        return
        except asyncio.CancelledError:
            raise
        except Exception as exc:
            logger.error("VoiceDesign monitor error for job %s: %s", job_id, exc)
            async with factory() as db:
                job = await db.get(VoiceDesignJobModel, job_id)
                if job and job.status not in ("completed", "failed", "cancelled"):
                    job.status = "failed"
                    job.error_message = str(exc)
                    await db.commit()
        finally:
            try:
                async with factory() as db:
                    acc = await db.get(KaggleAccountModel, account_id)
                    if acc and acc.status == "in_use":
                        acc.status = "available"
                        await db.commit()
            except Exception as exc:
                logger.warning("Could not reset Kaggle account %s status: %s", account_id, exc)

    @classmethod
    async def get_job(cls, job_id: str, user_id: str, db: AsyncSession) -> VoiceDesignJobModel:
        job = await db.get(VoiceDesignJobModel, job_id)
        if not job or job.user_id != user_id:
            raise NotFoundError(f"VoiceDesign job '{job_id}' not found")
        return job

    @classmethod
    async def list_project_jobs(
        cls,
        project_id: str,
        user_id: str,
        db: AsyncSession,
        limit: int = 20,
    ) -> list[VoiceDesignJobModel]:
        stmt = (
            select(VoiceDesignJobModel)
            .where(
                VoiceDesignJobModel.project_id == project_id,
                VoiceDesignJobModel.user_id == user_id,
            )
            .order_by(VoiceDesignJobModel.created_at.desc())
            .limit(limit)
        )
        return list((await db.execute(stmt)).scalars().all())
