class SfxDesignService:
    @classmethod
    async def _select_kaggle_account(
        cls,
        user_id: str,
        db: AsyncSession,
        kaggle_account_id: str | None = None,
    ) -> KaggleAccountModel:
        if kaggle_account_id:
            acc = await db.get(KaggleAccountModel, kaggle_account_id)
            if not acc or acc.user_id != user_id:
                raise NotFoundError(f"Kaggle account '{kaggle_account_id}' not found")
            return acc

        stmt = (
            select(KaggleAccountModel)
            .where(
                KaggleAccountModel.user_id == user_id,
                KaggleAccountModel.is_active.is_(True),
            )
            .order_by(KaggleAccountModel.created_at.asc())
        )
        accounts = list((await db.execute(stmt)).scalars().all())
        if not accounts:
            raise ValidationError(
                "No active Kaggle GPU account configured. Please add a Kaggle account in Profile settings."
            )
        available = [a for a in accounts if a.status == "available"]
        return available[0] if available else accounts[0]

    @classmethod
    async def start_sfx_design_job(
        cls,
        payload: SfxDesignRequestSchema,
        user_id: str,
        db: AsyncSession,
    ) -> SfxDesignJobModel:
        """Launch a batched Kaggle TangoFlux (44.1kHz) job for requested Foley / Atmosphere items."""
        project = await db.get(ProjectModel, payload.project_id)
        if not project:
            raise NotFoundError(f"Project '{payload.project_id}' not found")

        account = await cls._select_kaggle_account(
            user_id=user_id,
            db=db,
            kaggle_account_id=payload.kaggle_account_id,
        )

        item_configs: list[dict[str, Any]] = []
        initial_results: list[dict[str, Any]] = []
        for idx, item in enumerate(payload.items):
            asset_key = (item.asset_key or f"sfx_{idx}_{_slugify(item.name)}").strip()
            item_is_global = payload.is_global if item.is_global is None else bool(item.is_global)
            cfg = {
                "asset_key": asset_key,
                "name": item.name.strip(),
                "prompt": item.prompt.strip(),
                "category": item.category,
                "duration_seconds": float(item.duration_seconds),
                "default_volume": float(item.default_volume),
                "triggers": [t.strip() for t in item.triggers if t and t.strip()],
                "is_global": item_is_global,
                "replace_sfx_id": item.replace_sfx_id,
            }
            item_configs.append(cfg)
            initial_results.append(
                {
                    "asset_key": asset_key,
                    "name": cfg["name"],
                    "category": cfg["category"],
                    "prompt": cfg["prompt"],
                    "duration_seconds": cfg["duration_seconds"],
                    "status": "pending",
                    "applied_cues_count": 0,
                }
            )

        pending_cues = [c.model_dump() for c in payload.pending_cues]
        pending_spans = [s.model_dump() for s in payload.pending_atmosphere_spans]

        job_id = str(uuid.uuid4())
        job = SfxDesignJobModel(
            id=job_id,
            project_id=payload.project_id,
            user_id=user_id,
            kaggle_account_id=account.id,
            status="pending",
            auto_apply_cues=payload.auto_apply_cues,
            is_global=payload.is_global,
            cache_to_dataset=payload.cache_to_dataset,
            total_items=len(item_configs),
            completed_items=0,
            progress_percentage=0,
            current_step=f"Dispatching TangoFlux (44.1kHz) on @{account.username}...",
            item_configs=item_configs,
            pending_cues=pending_cues,
            pending_atmosphere_spans=pending_spans,
            results=initial_results,
        )
        db.add(job)
        await db.commit()
        await db.refresh(job)

        await cls._dispatch_kaggle_notebook(job=job, account=account, db=db)

        task = asyncio.create_task(cls._monitor_sfx_design_job(job.id, account.id))
        ACTIVE_SFX_DESIGN_TASKS[job.id] = task
        task.add_done_callback(lambda _: ACTIVE_SFX_DESIGN_TASKS.pop(job.id, None))
        return job

