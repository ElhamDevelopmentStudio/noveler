def to_mono_float32(audio_tensor) -> np.ndarray:
    if hasattr(audio_tensor, "detach"):
        arr = audio_tensor.detach().cpu().float().numpy()
    else:
        arr = np.asarray(audio_tensor, dtype=np.float32)
    arr = np.squeeze(arr)
    if arr.ndim == 2:
        # Handle (channels, samples) or (samples, channels)
        if arr.shape[0] <= 2 and arr.shape[1] > arr.shape[0]:
            arr = arr.mean(axis=0)
        else:
            arr = arr.mean(axis=1)
    return np.nan_to_num(arr, nan=0.0, posinf=0.0, neginf=0.0).astype(np.float32)

def normalize_peak(wav: np.ndarray, target_peak: float = 0.89) -> np.ndarray:
    peak = float(np.max(np.abs(wav))) if wav.size > 0 else 0.0
    if peak > 1e-6:
        wav = wav * (target_peak / peak)
    return np.clip(wav, -1.0, 1.0)

def postprocess_foley(wav: np.ndarray, sr: int = SAMPLE_RATE) -> np.ndarray:
    """Trim leading/trailing silence and apply short 15ms fades for crisp inline splicing."""
    wav = normalize_peak(wav)
    if wav.size < int(sr * 0.1):
        return wav
    win = max(1, int(sr * 0.02))
    abs_w = np.abs(wav)
    # Threshold at ~-38dB relative to peak
    thresh = 0.012
    active = np.where(abs_w > thresh)[0]
    if active.size > 0:
        start = max(0, int(active[0]) - int(sr * 0.025))
        end = min(wav.size, int(active[-1]) + int(sr * 0.08))
        if end - start >= int(sr * 0.12):
            wav = wav[start:end]
    fade = min(int(sr * 0.015), wav.size // 4)
    if fade > 1:
        wav = wav.copy()
        wav[:fade] *= np.linspace(0.0, 1.0, fade, dtype=np.float32)
        wav[-fade:] *= np.linspace(1.0, 0.0, fade, dtype=np.float32)
    return normalize_peak(wav)

def postprocess_atmosphere(wav: np.ndarray, sr: int = SAMPLE_RATE) -> np.ndarray:
    """Overlap-crossfade tail onto head so atmosphere tracks loop seamlessly."""
    wav = normalize_peak(wav, target_peak=0.85)
    xfade = int(sr * 1.5)
    if wav.size > xfade * 3:
        head = wav[:xfade]
        tail = wav[-xfade:]
        body = wav[xfade:-xfade]
        ramp = np.linspace(0.0, 1.0, xfade, dtype=np.float32)
        blended = head * ramp + tail * (1.0 - ramp)
        wav = np.concatenate([blended, body])
    return normalize_peak(wav, target_peak=0.85)

