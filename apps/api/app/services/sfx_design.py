    @classmethod
    async def apply_sfx_plan(
        cls,
        *,
        project_id: str,
        user_id: str,
        payload: ApplySfxPlanRequestSchema,
        db: AsyncSession,
        asset_key_to_sfx: dict[str, SFXModel] | None = None,
    ) -> ApplySfxPlanResponseSchema:
        """Apply reviewed Foley cues (default action='replace') and Atmosphere spans to project segments."""
        project = await db.get(ProjectModel, project_id)
        if not project:
            raise NotFoundError(f"Project '{project_id}' not found")

        asset_map = dict(asset_key_to_sfx or {})

        # Preload all referenced existing sfx_ids
        referenced_ids = {
            c.sfx_id for c in payload.foley_cues if c.sfx_id
        } | {
            s.sfx_id for s in payload.atmosphere_spans if s.sfx_id
        }
        sfx_by_id: dict[str, SFXModel] = {}
        if referenced_ids:
            sfx_stmt = select(SFXModel).where(
                SFXModel.user_id == user_id,
                SFXModel.id.in_(list(referenced_ids)),
            )
            sfx_by_id = {s.id: s for s in (await db.execute(sfx_stmt)).scalars().all()}

        def _resolve_sfx(sfx_id: str | None, asset_key: str | None) -> SFXModel | None:
            if sfx_id and sfx_id in sfx_by_id:
                return sfx_by_id[sfx_id]
            if asset_key and asset_key in asset_map:
                return asset_map[asset_key]
            return None

        # Collect all segment IDs we need to touch
        foley_seg_ids = {c.segment_id for c in payload.foley_cues if c.segment_id}
        atmo_seg_ids: set[str] = set()
        for span in payload.atmosphere_spans:
            if span.segment_ids:
                atmo_seg_ids.update(span.segment_ids)
            else:
                if span.start_segment_id:
                    atmo_seg_ids.add(span.start_segment_id)
                if span.end_segment_id:
                    atmo_seg_ids.add(span.end_segment_id)

        all_seg_ids = foley_seg_ids | atmo_seg_ids
        if not all_seg_ids:
            return ApplySfxPlanResponseSchema(
                applied_foley_count=0,
                applied_atmosphere_segments=0,
                message="No approved cues or atmosphere spans to apply.",
            )

        seg_stmt = (
            select(ScriptSegmentModel)
            .join(ChapterModel, ScriptSegmentModel.chapter_id == ChapterModel.id)
            .where(
                ChapterModel.project_id == project_id,
                ScriptSegmentModel.id.in_(list(all_seg_ids)),
            )
        )
        segs_by_id = {s.id: s for s in (await db.execute(seg_stmt)).scalars().all()}

        applied_foley = 0
        for cue in payload.foley_cues:
            seg = segs_by_id.get(cue.segment_id)
            sfx = _resolve_sfx(cue.sfx_id, cue.asset_key)
            if not seg or not sfx:
                continue

            action = cue.action if cue.action in ("replace", "alongside", "after") else "replace"
            audio_url = SFXService.get_presigned_url(sfx.audio_storage_key) or ""
            existing = [c for c in (seg.sfx_cues or []) if c.get("sfx_id") != sfx.id]
            existing.append(
                {
                    "id": str(uuid.uuid4()),
                    "sfx_id": sfx.id,
                    "sfx_name": sfx.name,
                    "audio_url": audio_url,
                    "target_text": (cue.target_text or "").strip(),
                    "action": action,
                    "volume": max(0.0, min(1.0, float(cue.volume))),
                }
            )
            seg.sfx_cues = existing
            seg.updated_at = datetime.now(UTC)
            applied_foley += 1

        applied_atmo = 0
        for span in payload.atmosphere_spans:
            sfx = _resolve_sfx(span.sfx_id, span.asset_key)
            if not sfx:
                continue

            target_ids = list(span.segment_ids) if span.segment_ids else []
            if not target_ids and span.start_segment_id and span.end_segment_id:
                start_seg = segs_by_id.get(span.start_segment_id)
                end_seg = segs_by_id.get(span.end_segment_id)
                if start_seg and end_seg and start_seg.chapter_id == end_seg.chapter_id:
                    span_stmt = (
                        select(ScriptSegmentModel)
                        .where(
                            ScriptSegmentModel.chapter_id == start_seg.chapter_id,
                            ScriptSegmentModel.order_index >= min(start_seg.order_index, end_seg.order_index),
                            ScriptSegmentModel.order_index <= max(start_seg.order_index, end_seg.order_index),
                        )
                    )
                    for sp_seg in (await db.execute(span_stmt)).scalars().all():
                        segs_by_id[sp_seg.id] = sp_seg
                        target_ids.append(sp_seg.id)

            vol = max(0.0, min(1.0, float(span.volume)))
            for sid in target_ids:
                seg = segs_by_id.get(sid)
                if not seg:
                    continue
                seg.atmosphere_id = sfx.id
                seg.atmosphere_name = sfx.name
                seg.atmosphere_volume = vol
                seg.updated_at = datetime.now(UTC)
                applied_atmo += 1

        await db.commit()
        return ApplySfxPlanResponseSchema(
            applied_foley_count=applied_foley,
            applied_atmosphere_segments=applied_atmo,
            message=f"Applied {applied_foley} foley cue(s) and {applied_atmo} atmosphere segment(s).",
        )

    @classmethod
    async def ingest_receipt_into_sfx(
        cls,
        job_id: str,
        receipt: dict[str, Any],
        db: AsyncSession,
    ) -> SfxDesignJobModel:
        """Idempotently register completed TangoFlux clips into SFXModel and auto-apply pending cues."""
        job = await db.get(SfxDesignJobModel, job_id)
        if not job:
            raise NotFoundError(f"SFX Design job '{job_id}' not found")

        existing_by_key = {
            r["asset_key"]: dict(r) for r in (job.results or []) if "asset_key" in r
        }
        updated_results: list[dict[str, Any]] = []
        completed_count = 0
        asset_key_to_sfx: dict[str, SFXModel] = {}

        for item in receipt.get("results", []):
            asset_key = item["asset_key"]
            prev = existing_by_key.get(asset_key, {})
            status = item.get("status", "pending")

            if status == "completed":
                completed_count += 1
                sfx_id = prev.get("sfx_id")
                audio_url = prev.get("audio_url")

                if not sfx_id and item.get("audio_storage_key"):
                    replace_id = item.get("replace_sfx_id")
                    sfx_obj: SFXModel | None = None
                    if replace_id:
                        candidate = await db.get(SFXModel, replace_id)
                        if candidate and candidate.user_id == job.user_id:
                            candidate.audio_storage_key = item["audio_storage_key"]
                            candidate.duration_seconds = item.get("duration_seconds")
                            candidate.updated_at = datetime.now(UTC)
                            sfx_obj = candidate

                    if sfx_obj is None:
                        item_is_global = (
                            job.is_global
                            if item.get("is_global") is None
                            else bool(item.get("is_global"))
                        )
                        category = (item.get("category") or "foley").lower()
                        if category not in ("foley", "atmosphere"):
                            category = "foley"
                        sfx_obj = SFXModel(
                            id=str(uuid.uuid4()),
                            user_id=job.user_id,
                            project_id=None if item_is_global else job.project_id,
                            name=(item.get("name") or "Generated SFX").strip(),
                            category=category,
                            is_global=item_is_global,
                            audio_storage_key=item["audio_storage_key"],
                            duration_seconds=item.get("duration_seconds"),
                            default_volume=float(
                                item.get("default_volume")
                                or (0.2 if category == "atmosphere" else 0.85)
                            ),
                            triggers=item.get("triggers") or [],
                        )
                        db.add(sfx_obj)

                    await db.flush()
                    sfx_id = sfx_obj.id
                    audio_url = SFXService.get_presigned_url(sfx_obj.audio_storage_key)
                    asset_key_to_sfx[asset_key] = sfx_obj
                elif sfx_id:
                    existing_sfx = await db.get(SFXModel, sfx_id)
                    if existing_sfx:
                        asset_key_to_sfx[asset_key] = existing_sfx

                updated_results.append(
                    {
                        "asset_key": asset_key,
                        "name": item.get("name") or prev.get("name", ""),
                        "category": item.get("category") or prev.get("category", "foley"),
                        "prompt": item.get("prompt") or prev.get("prompt", ""),
                        "duration_seconds": item.get("duration_seconds"),
                        "status": "completed",
                        "sfx_id": sfx_id,
                        "audio_url": audio_url,
                        "applied_cues_count": prev.get("applied_cues_count", 0),
                    }
                )
            elif status == "failed":
                completed_count += 1
                updated_results.append(
                    {
                        "asset_key": asset_key,
                        "name": item.get("name") or prev.get("name", ""),
                        "category": item.get("category") or prev.get("category", "foley"),
                        "prompt": item.get("prompt") or prev.get("prompt", ""),
                        "status": "failed",
                        "error": item.get("error") or "SFX generation failed",
                    }
                )
            else:
                updated_results.append(prev or item)

        job.results = updated_results
        job.completed_items = completed_count
        job.progress_percentage = (
            int(round((completed_count / max(1, job.total_items)) * 100))
            if job.total_items > 0
            else 100
        )
        if receipt.get("current_step"):
            job.current_step = receipt["current_step"]

        final_status = receipt.get("status")
        if final_status in ("completed", "failed"):
            job.status = final_status
            if receipt.get("error_message"):
                job.error_message = receipt["error_message"]

            # Auto-apply approved script cues once batch finishes
            if (
                final_status == "completed"
                and job.auto_apply_cues
                and (job.pending_cues or job.pending_atmosphere_spans)
            ):
                plan_req = ApplySfxPlanRequestSchema(
                    foley_cues=job.pending_cues or [],
                    atmosphere_spans=job.pending_atmosphere_spans or [],
                )
                apply_res = await cls.apply_sfx_plan(
                    project_id=job.project_id,
                    user_id=job.user_id,
                    payload=plan_req,
                    db=db,
                    asset_key_to_sfx=asset_key_to_sfx,
                )
                job.current_step = (
                    f"Completed · {apply_res.applied_foley_count} foley cue(s) & "
                    f"{apply_res.applied_atmosphere_segments} atmosphere seg(s) applied"
                )
                # Clear pending cues so re-ingestion stays idempotent
                job.pending_cues = []
                job.pending_atmosphere_spans = []

        job.updated_at = datetime.now(UTC)
        await db.commit()
        await db.refresh(job)
        return job

    @classmethod
    async def _monitor_sfx_design_job(cls, job_id: str, account_id: str) -> None:
        """Poll R2 for Kaggle TangoFlux receipts until completed/failed or timeout."""
        factory = get_session_factory()
        receipt_key = f"jobs/sfx-design/{job_id}/receipt.json"
        max_polls = 360  # up to 30 minutes at 5s interval

        try:
            for _ in range(max_polls):
                await asyncio.sleep(5.0)
                s3 = get_s3_client()
                if not s3 or not settings.is_r2_configured:
                    break

                def _fetch_receipt():
                    try:
                        obj = s3.get_object(Bucket=settings.R2_BUCKET, Key=receipt_key)
                        return json.loads(obj["Body"].read().decode("utf-8"))
                    except Exception:
                        return None

                receipt = await asyncio.to_thread(_fetch_receipt)
                if not receipt:
                    continue

                async with factory() as db:
                    job = await cls.ingest_receipt_into_sfx(job_id, receipt, db)
                    if job.status in ("completed", "failed", "cancelled"):
                        return
        except asyncio.CancelledError:
            raise
        except Exception as exc:
            logger.error("SFX Design monitor error for job %s: %s", job_id, exc)
            async with factory() as db:
                job = await db.get(SfxDesignJobModel, job_id)
                if job and job.status not in ("completed", "failed", "cancelled"):
                    job.status = "failed"
                    job.error_message = str(exc)
                    await db.commit()
        finally:
            try:
                async with factory() as db:
                    acc = await db.get(KaggleAccountModel, account_id)
                    if acc and acc.status == "in_use":
                        acc.status = "available"
                        await db.commit()
            except Exception as exc:
                logger.warning("Could not reset Kaggle account %s status: %s", account_id, exc)

    @classmethod
    async def get_job(cls, job_id: str, user_id: str, db: AsyncSession) -> SfxDesignJobModel:
        job = await db.get(SfxDesignJobModel, job_id)
        if not job or job.user_id != user_id:
            raise NotFoundError(f"SFX Design job '{job_id}' not found")
        return job

    @classmethod
    async def list_project_jobs(
        cls,
        project_id: str,
        user_id: str,
        db: AsyncSession,
        limit: int = 20,
    ) -> list[SfxDesignJobModel]:
        stmt = (
            select(SfxDesignJobModel)
            .where(
                SfxDesignJobModel.project_id == project_id,
                SfxDesignJobModel.user_id == user_id,
            )
            .order_by(SfxDesignJobModel.created_at.desc())
            .limit(limit)
        )
        return list((await db.execute(stmt)).scalars().all())
